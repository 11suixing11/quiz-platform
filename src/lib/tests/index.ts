export async function loadTestData(type: string): Promise<TestData | null> {
  const loader = registry[type];
  if (!loader) return null;
  try {
    const mod = await loader();
    const data = mod.default as TestData;
    if (!data || !data.questions) {
      console.error('loadTestData: invalid data for', type);
      return null;
    }
    return data;
  } catch (e) {
    console.error('loadTestData error:', type, e);
    return null;
  }
}

export function isTestRegistered(type: string): boolean {
  return type in registry;
}